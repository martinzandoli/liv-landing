const ICONOS = { Instagram: IconoInstagram, TikTok: IconoTikTok, X: IconoX };
export const REDES = DATOS.map((r) => ({ ...r, Icono: ICONOS[r.red] }));

/* Botón flotante de WhatsApp, en blanco y negro como el resto de la marca */
export function WhatsAppFlotante() {
  const [visible, setVisible] = useState(false);

  useEffect(() => {
    // después del hero; se esconde al llegar al pie, donde ya está el contacto
    const onScroll = () => {
      const alFinal = document.documentElement.scrollHeight - (window.scrollY + window.innerHeight) < 480;
      setVisible(window.scrollY > window.innerHeight * 0.7 && !alFinal);
    };
    onScroll();
    window.addEventListener("scroll", onScroll, { passive: true });
    return () => window.removeEventListener("scroll", onScroll);
  }, []);

  return (
    <AnimatePresence>
      {visible && (
        <motion.a
          key="wsp"
          href={WHATSAPP.href}
          target="_blank"
          rel="noopener noreferrer"
          aria-label={`Escribinos por WhatsApp al ${WHATSAPP.numero}`}
          initial={{ opacity: 0, scale: 0.6, y: 16 }}
          animate={{ opacity: 1, scale: 1, y: 0 }}
          exit={{ opacity: 0, scale: 0.6, y: 16 }}
          transition={{ duration: 0.45, ease: EASE }}
          className="group fixed bottom-4 right-4 z-40 flex h-14 items-center gap-0 overflow-hidden rounded-full bg-ink pl-[17px] pr-[17px] text-white shadow-[0_10px_30px_-10px_rgba(0,0,0,0.55)] ring-1 ring-white/15 md:bottom-6 md:right-6"
        >
          <IconoWhatsApp className="h-[22px] w-[22px] shrink-0" />
          <span className="max-w-0 whitespace-nowrap text-[14px] font-semibold opacity-0 transition-all duration-500 ease-[cubic-bezier(.2,.7,.1,1)] group-hover:ml-2.5 group-hover:max-w-[12rem] group-hover:opacity-100">
            Escribinos
          </span>
        </motion.a>
      )}
    </AnimatePresence>
  );
}
